from __future__ import annotations

import sys

import pandas as pd

from pilot_common import OUT_DIR, ROOT
from report_tables import md

sys.path.insert(0, str(ROOT))
from common.config import MIN_GAMMA, REWARDS, indifference_point  # noqa: E402

OUT = OUT_DIR / "reward_final_v2"
CONFIGS = ["low", "medium", "high"]
VARIANTS = ["default", "efficiency", "balanced", "safety"]
GAMMAS = [1.0, 0.99, 0.9, 0.8]


def f(x, d=2) -> str:
    return "n/a" if pd.isna(x) else f"{x:.{d}f}"


def pc(x) -> str:
    return "n/a" if pd.isna(x) else f"{100 * x:.0f}%"


def weights_table() -> str:
    rows = [{"reward": "default", "w_speed": "-", "w_right": "-", "w_lane": "-", "w_collision": "- (env's normalized reward)", "analytic p": "-"}]
    for v in VARIANTS[1:]:
        w = REWARDS[v]
        rows.append({"reward": v, "w_speed": f(w["w_speed"]), "w_right": f(w["w_right"]), "w_lane": f(w["w_lane"]),
                     "w_collision": f(w["w_collision"]),
                     "analytic p": f(indifference_point(w["w_speed"], w["w_right"], w["w_collision"]))})
    return md(pd.DataFrame(rows))


def main_table(k: pd.DataFrame, gamma: float) -> str:
    rows = []
    for c in CONFIGS:
        for v in VARIANTS:
            x = k[(k.gamma == gamma) & (k.config == c) & (k.reward == v)].iloc[0]
            ci = f"{f(x.p)} ({f(x.p_boot_lo)}-{f(x.p_boot_hi)})" if x.order_ok else f"n/a (order holds in {pc(x.order_boot_frac)})"
            rows.append({
                "config": c, "reward": v,
                "G_crash": f(x.G_crash), "G_slow": f(x.G_slow),
                "G_succ": f"{f(x.G_succ)} ({'F' if x.succ_source == 'faster' else 'I'}, n={int(x.n_succ)})",
                "order": ("**OK**" if x.order_ok else "**FAILS**") + f" ({pc(x.order_boot_frac)})",
                "empirical p (90%)": ci, "analytic p (gamma = 1)": f(x.target_p),
                "empirical - analytic": ("%+.2f" % x.p_minus_target) if pd.notna(x.p_minus_target) else "n/a",
                "analytic p at this gamma": f(x.analytic_p_at_gamma),
            })
    return md(pd.DataFrame(rows))


def matrix_table(k: pd.DataFrame) -> str:
    rows = []
    for c in CONFIGS:
        for v in VARIANTS:
            row = {"config": c, "reward": v, "analytic p": f(k[(k.config == c) & (k.reward == v)].target_p.iloc[0])}
            for g in GAMMAS:
                x = k[(k.gamma == g) & (k.config == c) & (k.reward == v)].iloc[0]
                row[f"gamma={g:g}"] = (f"OK, p={f(x.p)}" if x.order_ok else "FAILS") + f" ({pc(x.order_boot_frac)})"
            rows.append(row)
    return md(pd.DataFrame(rows))


def window_table(k: pd.DataFrame) -> str:
    rows = []
    for g in GAMMAS[1:]:
        for c in CONFIGS:
            row = {"gamma": f"{g:g}", "config": c}
            for v in VARIANTS:
                x = k[(k.gamma == g) & (k.config == c) & (k.reward == v)].iloc[0]
                row[v] = f"{f(x.win_crash, 1)} vs {f(x.win_succ, 1)}"
            rows.append(row)
    return md(pd.DataFrame(rows))


def penalty_term_table(k: pd.DataFrame) -> str:
    rows = []
    for g in GAMMAS:
        row = {"gamma": f"{g:g}"}
        for v in VARIANTS:
            x = k[(k.gamma == g) & (k.config == "medium") & (k.reward == v)].iloc[0]
            row[v] = f(x.collision_term_in_window, 1)
        rows.append(row)
    return md(pd.DataFrame(rows))


