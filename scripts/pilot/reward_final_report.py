def main() -> None:
    k = pd.read_csv(OUT / "knox_final.csv")
    text = (
        TEMPLATE.replace("@@WEIGHTS@@", weights_table())
        .replace("@@MINGAMMA@@", str(MIN_GAMMA))
        .replace("@@G1@@", main_table(k, 1.0))
        .replace("@@MATRIX@@", matrix_table(k))
        .replace("@@G099@@", main_table(k, 0.99))
        .replace("@@G09@@", main_table(k, 0.9))
        .replace("@@G08@@", main_table(k, 0.8))
        .replace("@@WINDOW@@", window_table(k))
        .replace("@@PENALTY@@", penalty_term_table(k))
    )
    (OUT / "REWARD_FINAL_V2.md").write_text(text, encoding="utf-8")
    print("wrote", OUT / "REWARD_FINAL_V2.md", f"({len(text)} chars)")


if __name__ == "__main__":
    main()
